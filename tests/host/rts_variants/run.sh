# Tests for the variant build of the runtime (crates/mpfs_rts/gen_runtime.sh and mpfs_rts.gpr):
# the arguments are validated before anything is built; a variant is built from its pack into
# adainclude/, adalib/ (libgnat.a, libgnarl.a unless light) and ld/ with the stamp; a second run
# does not build again (same libgnat.a, same inode, same stamp); a changed port unit, a changed
# overlay and a changed pack (switch BUILD) change the key and rebuild, --check says so without
# building; the pack comes from make_packs.sh --ensure: a missing pack is not generated by --check
# but by a build, a warm pack is not generated again (also with the runtime missing), a damaged
# one is regenerated and gives the same key; mpfs_rts.gpr names the
# directory of the variant from the scenario variables and rejects values outside the variants.
# The builds are skipped when the pinned GNAT is not installed (./x toolchain install gnat) and
# the pack cases when zstd or GNU tar is missing. Exits non-zero on any failure.

set -u
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
CRATE="$ROOT/crates/mpfs_rts"
GEN="$CRATE/gen_runtime.sh"
fails=0

pass () { echo "ok:   $1"; }
fail () { echo "FAIL: $1" >&2; fails=$((fails + 1)); }
skip () { echo "skip: $1"; }

# expect_out <description> <expected exit code> <text that must be in stderr+stdout> <command...>
expect_out () {
  local desc="$1" want="$2" text="$3"; shift 3
  local out rc
  out="$("$@" 2>&1)"; rc=$?
  if [ "$rc" != "$want" ]; then fail "$desc (exit $rc, wanted $want: $out)"; return; fi
  case "$out" in *"$text"*) pass "$desc" ;; *) fail "$desc (no \"$text\" in: $out)" ;; esac
}

work="$(mktemp -d)"
trap 'chmod -R u+w "$work" 2>/dev/null; rm -rf "$work"' EXIT
out="$work/rts"

# -- arguments: all rejected before a pack is unpacked or the toolchain is looked at ------------
expect_out "a wrong number of arguments is a set-up error" 2 "usage: gen_runtime.sh" bash "$GEN" light e51 1
expect_out "an unknown profile is rejected" 2 "invalid profile 'full'" bash "$GEN" --out "$out" full e51 1 m
expect_out "an unknown hart is rejected" 2 "invalid hart 'e52'" bash "$GEN" --out "$out" light e52 1 m
expect_out "cpus 2 is rejected (P8)" 2 "single-CPU until" bash "$GEN" --out "$out" light-tasking u54 2 m
expect_out "cpus 0 is rejected" 2 "invalid cpus '0'" bash "$GEN" --out "$out" light e51 0 m
expect_out "priv u is rejected (P7)" 2 "M mode until" bash "$GEN" --out "$out" light e51 1 u
expect_out "an unknown option is rejected" 2 "unknown option '--bogus'" bash "$GEN" --bogus light e51 1 m
expect_out "an unknown build mode is rejected" 2 "invalid MPFS_RTS_BUILD 'Fast'" env MPFS_RTS_BUILD=Fast bash "$GEN" --out "$out" light e51 1 m
expect_out "--hashes needs a file" 2 "--hashes needs a file" bash "$GEN" --out "$out" --hashes
[ ! -e "$out" ] && pass "a rejected call builds and creates nothing" || fail "a rejected call builds and creates nothing"

# -- mpfs_rts.gpr: values outside the variants are rejected by the project ------------------------
. "$ROOT/tools/mpfs-env.sh"
if mpfs_toolchain_on_path >/dev/null 2>&1; then have_tc=1; else have_tc=0; fi
mkdir -p "$work/gpr/src"
cat > "$work/gpr/q.gpr" <<EOF
with "$CRATE/mpfs_rts.gpr";
project Q is
   for Source_Dirs use ("src");
   for Object_Dir use "obj";
   for Languages use ("Ada");
   for Target use Mpfs_Rts.Target;
   for Runtime ("Ada") use Mpfs_Rts.Runtime_Path;
end Q;
EOF
echo 'package T is pragma Pure; end T;' > "$work/gpr/src/t.ads"
if [ $have_tc = 1 ]; then
  for bad in "MPFS_PROFILE=full:illegal for typed string" "MPFS_HART=e52:illegal for typed string" \
             "MPFS_CPUS=2:illegal for typed string" "MPFS_PRIV=u:illegal for typed string"; do
    expect_out "mpfs_rts.gpr: ${bad%%:*} is rejected" 4 "${bad#*:}" \
      bash -c "cd '$work/gpr' && gprbuild -c -P q.gpr -X${bad%%:*}; rc=\$?; [ \$rc -eq 0 ] || exit 4"
  done
fi

# -- the builds ---------------------------------------------------------------------------------
if [ $have_tc = 0 ]; then
  skip "builds: the pinned toolchain is not installed (./x toolchain install gnat)"
elif ! command -v zstd >/dev/null 2>&1 || ! tar --version 2>&1 | grep -q 'GNU tar'; then
  skip "builds: zstd or GNU tar is not installed"
else
  v="$out/light-e51-cpus1-m"

  expect_out "--check before the first build: not up to date" 1 "not up to date" bash "$GEN" --check --out "$out" light e51 1 m
  [ ! -e "$out" ] && pass "--check builds nothing" || fail "--check builds nothing"
  expect_out "--check with a missing pack: not up to date, and no pack is generated" 1 "is not generated" \
    bash "$GEN" --check --out "$out" --packs "$work/nopacks" light e51 1 m
  [ ! -e "$work/nopacks" ] && pass "--check generates no pack" || fail "--check generates no pack"

  bash "$GEN" --out "$out" light e51 1 m >"$work/first.out" 2>&1; rc=$?
  if [ $rc -eq 0 ] && grep -q "gen_runtime: built light-e51-cpus1-m" "$work/first.out"; then pass "light e51: built"
  else fail "light e51: built (exit $rc: $(tail -5 "$work/first.out"))"; fi
  for f in adalib/libgnat.a adainclude/system.ads adainclude/s-textio.adb runtime.xml COPYING3 COPYING.RUNTIME .mpfs_rts.stamp; do
    [ -f "$v/$f" ] && pass "light e51: $f" || fail "light e51: $f"
  done
  [ -d "$v/ld" ] && pass "light e51: ld/" || fail "light e51: ld/"
  [ ! -e "$v/adalib/libgnarl.a" ] && pass "light e51: no libgnarl.a" || fail "light e51: no libgnarl.a"
  [ ! -e "$v/obj" ] && [ ! -e "$v/gnat" ] && [ ! -e "$v/ada_source_path" ] && pass "light e51: no build leftovers" \
    || fail "light e51: no build leftovers"
  grep -q '/ld"' "$v/runtime.xml" && ! grep -q ld_user "$v/runtime.xml" && pass "light e51: runtime.xml links from ld/" \
    || fail "light e51: runtime.xml links from ld/"
  grep -q 'rv64imac_zicsr_zifencei' "$v/runtime.xml" && pass "light e51: -march of the E51" || fail "light e51: -march of the E51"
  want="$(awk '$2 == "light-e51.tar" { print $1 }' "$CRATE/packs.sha256")"
  grep -q "^pack_sha256=$want$" "$v/.mpfs_rts.stamp" \
    && pass "light e51: the stamp has the hash of packs.sha256" || fail "light e51: the stamp has the hash of packs.sha256"
  flags="$(riscv64-elf-readelf -h "$v/adalib/libgnat.a" 2>/dev/null | grep -m1 Flags)"
  case "$flags" in *soft-float*) pass "light e51: objects are soft-float" ;; *) fail "light e51: objects are soft-float ($flags)" ;; esac

  # A second run does not build again.
  sum1="$(cksum < "$v/.mpfs_rts.stamp")"; ino1="$(stat -c '%i %Y' "$v/adalib/libgnat.a")"
  expect_out "second run: up to date" 0 "is up to date" bash "$GEN" --out "$out" light e51 1 m
  [ "$sum1" = "$(cksum < "$v/.mpfs_rts.stamp")" ] && [ "$ino1" = "$(stat -c '%i %Y' "$v/adalib/libgnat.a")" ] \
    && pass "second run: libgnat.a and the stamp are untouched" || fail "second run: libgnat.a and the stamp are untouched"
  expect_out "--check after the build: up to date" 0 "is up to date" bash "$GEN" --check --out "$out" light e51 1 m

  # mpfs_rts.gpr names the directory of the variant: a project compiles against the built one
  # and, for a variant that is not built, fails naming the directory it looked for.
  ( cd "$work/gpr" && MPFS_RTS_ROOT="$out" gprbuild -c -p -P q.gpr -XMPFS_PROFILE=light -XMPFS_HART=e51 ) >"$work/gpr.out" 2>&1 \
    && pass "mpfs_rts.gpr: a project compiles against build/rts/light-e51-cpus1-m" \
    || fail "mpfs_rts.gpr: a project compiles against build/rts/light-e51-cpus1-m ($(tail -3 "$work/gpr.out"))"
  out2="$( cd "$work/gpr" && MPFS_RTS_ROOT="$out" gprbuild -c -p -P q.gpr -XMPFS_PROFILE=light -XMPFS_HART=u54 2>&1 )"; rc=$?
  case "$out2" in
    *"$out/light-u54-cpus1-m"*) [ $rc -ne 0 ] && pass "mpfs_rts.gpr: a variant that is not built fails and names its directory" \
                                              || fail "mpfs_rts.gpr: a variant that is not built fails" ;;
    *) fail "mpfs_rts.gpr: the failure names light-u54-cpus1-m ($out2)" ;;
  esac

  # A missing file makes the variant stale although the stamp fits.
  mv "$v/adalib/libgnat.a" "$work/libgnat.a.saved"
  expect_out "a missing libgnat.a: not up to date" 1 "not up to date" bash "$GEN" --check --out "$out" light e51 1 m
  mv "$work/libgnat.a.saved" "$v/adalib/libgnat.a"

  # Port units: a changed one changes the key (--check only, no build).
  mkdir -p "$work/port/gnat" "$work/ov/10-test/gnat" "$work/ov/10-test/ld"
  cp "$v/adainclude/s-textio.adb" "$work/port/gnat/s-textio.adb"
  expect_out "--check with a port unit: not up to date" 1 "not up to date" \
    bash "$GEN" --check --out "$out" --port-dir "$work/port" light e51 1 m
  echo "-- changed" >> "$work/port/gnat/s-textio.adb"
  expect_out "--check with another port unit: not up to date" 1 "not up to date" \
    bash "$GEN" --check --out "$out" --port-dir "$work/port" light e51 1 m
  # Overlays: an overlay replaces a source, adds to ld/, and the build uses it.
  cp "$v/adainclude/s-textio.adb" "$work/ov/10-test/gnat/s-textio.adb"
  echo "--  mpfs_rts overlay marker" >> "$work/ov/10-test/gnat/s-textio.adb"
  echo "/* overlay */" > "$work/ov/10-test/ld/overlay.ld"
  bash "$GEN" --out "$out" --overlay-dir "$work/ov" light e51 1 m >"$work/ov.out" 2>&1; rc=$?
  if [ $rc -eq 0 ] && grep -q "gen_runtime: built light-e51" "$work/ov.out"; then pass "a changed overlay rebuilds"
  else fail "a changed overlay rebuilds (exit $rc: $(tail -5 "$work/ov.out"))"; fi
  grep -q "overlay marker" "$v/adainclude/s-textio.adb" && pass "the overlay source is in adainclude/" || fail "the overlay source is in adainclude/"
  [ -f "$v/ld/overlay.ld" ] && pass "the overlay file is in ld/" || fail "the overlay file is in ld/"
  [ -f "$v/adalib/libgnat.a" ] && pass "the build with the overlay has libgnat.a" || fail "the build with the overlay has libgnat.a"
  expect_out "the same overlay again: up to date" 0 "is up to date" bash "$GEN" --out "$out" --overlay-dir "$work/ov" light e51 1 m
  expect_out "without the overlay: the key differs again" 1 "not up to date" bash "$GEN" --check --out "$out" light e51 1 m
  # The switches: the build mode is part of the key.
  expect_out "another build mode: not up to date" 1 "not up to date" env MPFS_RTS_BUILD=Debug bash "$GEN" --check --out "$out" light e51 1 m

  # The pack comes from make_packs.sh --ensure. The packs of the repository are generated by the
  # first build above if they were missing; a second variant with the runtime missing must not
  # generate them again.
  P="${MPFS_RTS_PACKS:-$ROOT/build/rts/packs}"
  ino1="$(stat -c '%i %Y' "$P/light-e51.tar.zst")"
  rm -rf "$out/light-e51-cpus1-m"
  bash "$GEN" --out "$out" light e51 1 m >"$work/warm.out" 2>&1; rc=$?
  if [ $rc -eq 0 ] && grep -q "gen_runtime: built light-e51" "$work/warm.out" \
     && ! grep -q "regenerating" "$work/warm.out" && [ "$ino1" = "$(stat -c '%i %Y' "$P/light-e51.tar.zst")" ]; then
    pass "a warm pack is not generated again when the runtime is missing"
  else fail "a warm pack is not generated again when the runtime is missing (exit $rc: $(tail -3 "$work/warm.out"))"; fi
  key1="$(sed -n 's/^key=//p' "$v/.mpfs_rts.stamp")"

  # A damaged pack (copy of the good one with a flipped tail) is regenerated, and the variant
  # gets the same key as before; the pack of the repository is not touched.
  mkdir -p "$work/packs"
  cp "$P/light-e51.tar.zst" "$work/packs/"
  printf 'x' >> "$work/packs/light-e51.tar.zst"
  bash "$GEN" --out "$work/rts2" --packs "$work/packs" light e51 1 m >"$work/dam.out" 2>&1; rc=$?
  if [ $rc -eq 0 ] && grep -q "regenerating" "$work/dam.out"; then pass "a damaged pack is regenerated"
  else fail "a damaged pack is regenerated (exit $rc: $(tail -3 "$work/dam.out"))"; fi
  [ "$key1" = "$(sed -n 's/^key=//p' "$work/rts2/light-e51-cpus1-m/.mpfs_rts.stamp" 2>/dev/null)" ] \
    && pass "the regenerated pack gives the same key" || fail "the regenerated pack gives the same key"

fi

[ $fails -eq 0 ] || { echo "$fails failure(s)" >&2; exit 1; }
echo "all ok"
