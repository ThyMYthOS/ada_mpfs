"""tools/gen_ada/ada.py: identifiers, comment wrapping, banners and the notice."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
sys.path[:0] = [str(HERE), str(ROOT / "tools")]

from gen_ada import ada, errors  # noqa: E402
from harness import case, finish, raises  # noqa: E402


class Mine(errors.GenError):
    pass


@case("identifier: upper-case names with single underscores and digits pass unchanged")
def _():
    for name in ("UART0", "L2_METADATA_CORR", "A", "U54_4_BUS_ERROR_UNIT", "X1_2"):
        assert ada.identifier(name, "here") == name


@case("identifier: lower case, a leading digit or underscore, a double or trailing underscore, a dash and the empty name are refused")
def _():
    for name in ("uart", "Uart0", "0A", "_A", "A__B", "A_", "A-B", "A B", ""):
        raises(errors.InputError, lambda n=name: ada.identifier(n, "svd: interrupt 3"),
               f"svd: interrupt 3: {name!r} is not an upper-case Ada identifier")


@case("identifier: a reserved word is refused, in any case the identifier rule lets through")
def _():
    for name in ("END", "ACCESS", "PARALLEL", "SOME", "XOR"):
        raises(errors.InputError, lambda n=name: ada.identifier(n, "w"), f"w: {name} is an Ada reserved word")
    assert ada.identifier("ENDS", "w") == "ENDS"


@case("identifier: the error class is the caller's")
def _():
    raises(Mine, lambda: ada.identifier("bad", "w", Mine), "not an upper-case")
    raises(Mine, lambda: ada.identifier("END", "w", Mine), "reserved word")


@case("the reserved words are the 74 of Ada 2022")
def _():
    assert len(ada.RESERVED) == 74 and {"abort", "xor", "parallel", "some", "synchronized"} <= ada.RESERVED


@case("comment: short text is one line after the indent")
def _():
    assert ada.comment("A short text.") == ["   --  A short text."]
    assert ada.comment("A short text.", "") == ["--  A short text."]
    assert ada.comment("x", "      ") == ["      --  x"]


@case("comment: no line is wider than 78 columns and no word is lost or split")
def _():
    text = " ".join(f"word{n}" for n in range(60))
    for indent in ("", "   ", "      "):
        lines = ada.comment(text, indent)
        assert all(len(line) <= ada.WIDTH for line in lines), [len(x) for x in lines]
        assert len(lines) > 1
        assert " ".join(line.split("--  ", 1)[1] for line in lines) == text


@case("comment: a line holds as many words as fit (the break is at 78 columns, not earlier)")
def _():
    lines = ada.comment(" ".join(["abcdefghi"] * 12), "")
    assert [len(x) for x in lines] == [73, 53], [len(x) for x in lines]


@case("comment: a word wider than a line stands alone; empty text is an empty comment line")
def _():
    long = "x" * 100
    assert ada.comment(f"a {long} b", "") == ["--  a", f"--  {long}", "--  b"]
    assert ada.comment("", "   ") == ["   --  "]
    assert ada.comment("  \n ", "") == ["--  "]


@case("comment: runs of blanks and newlines are one blank")
def _():
    assert ada.comment("a  b\n\tc") == ["   --  a b c"]


@case("banner: a three-line box as wide as the title")
def _():
    assert ada.banner("PLIC sources") == ["   ------------------", "   -- PLIC sources --", "   ------------------"]
    assert ada.banner("")[1] == "   --  --"


@case("generated_notice: says who generates the file from what, and that CI checks it")
def _():
    text = ada.generated_notice("tools/x.py", "the SVD")
    assert text == ("GENERATED by tools/x.py from the SVD. Do not edit: change the inputs and run the generator "
                    "(CI fails if this file is not current).")


finish()
