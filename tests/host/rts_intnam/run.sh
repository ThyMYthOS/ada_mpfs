# Tests for the names of the interrupts of the runtime (crates/mpfs_rts/gen_intnam.py and the generated
# crates/mpfs_rts/mpfs/gnarl/a-intnam.ads):
#
#   - the generator on small fixtures: the output (the PLIC sources of every peripheral, sorted by value, the
#     descriptions, the gap, the local interrupts in the package Local with their harts and PLIC source), the same
#     output for a shuffled input, --check (current: 0, changed or missing: 1), and every input that violates a
#     rule is refused with exit 2 and named: no interrupt, a double value, a double name, a name that is no
#     upper-case identifier or is an Ada reserved word, a first source that is not 1, an Interrupt_Range that is
#     not the range of the sources (too small, too large, missing), a local interrupt with an unknown hart, an unknown
#     PLIC source, a double name or a wrong schema;
#   - the committed a-intnam.ads is what the generator makes of the merged SVD (tools/svd.py ensure; skipped when
#     svdtools is needed and not installed), has 185 PLIC names for 1 .. 186 without a name for 117 (reserved or spare in the TRM, still an Interrupt_ID) and the same range as
#     Interrupt_Range of s-bbpara, and the runtime variants have it;
#   - with the real compiler against the runtime variant light-tasking-u54: the first and the last source are an
#     Interrupt_ID, 0 and 187 are not (a static value outside the range is rejected), a local interrupt number is
#     not an Interrupt_ID, and a copy of a-intnam.ads for another range does not compile (the compile-time check).
#
# Exits non-zero on any failure.
# @verifies SVD-002

set -u
export LC_ALL=C
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
HERE="$ROOT/tests/host/rts_intnam"
FIX="$HERE/fixtures"
GEN="$ROOT/crates/mpfs_rts/gen_intnam.py"
COMMITTED="$ROOT/crates/mpfs_rts/mpfs/gnarl/a-intnam.ads"
fails=0

pass () { echo "ok:   $1"; }
fail () { echo "FAIL: $1" >&2; fails=$((fails + 1)); }
skip () { echo "skip: $1"; }

. "$ROOT/tools/mpfs-env.sh"
mpfs_toolchain_on_path >/dev/null 2>&1 || true
mpfs_find_python
PY="$MPFS_PYTHON"

work="$(mktemp -d)"
trap 'chmod -R u+w "$work" 2>/dev/null; rm -rf "$work"' EXIT

# gen <extra arguments...>: the generator on the fixtures, output in $work/out.ads; sets $rc and $out
gen () {
  out="$("$PY" "$GEN" --svd "${SVD:-$FIX/device.svd}" --local "${LOCAL:-$FIX/local.yaml}" \
          --parameters "${PARAMS:-$FIX/parameters.ads}" --output "${OUT:-$work/out.ads}" "$@" 2>&1)"
  rc=$?
}

# refused <description> <pattern>: the last gen call exited with 2 and the message has the pattern
refused () {
  if [ "$rc" = 2 ] && printf '%s' "$out" | grep -q -- "$2"; then pass "$1"
  else fail "$1 (exit $rc: $(printf '%s' "$out" | head -3 | tr '\n' ' '))"; fi
}

has () { grep -qF -- "$2" "$3" && pass "$1" || fail "$1 (no '$2' in $3)"; }

if "$PY" -c 'import yaml' 2>/dev/null; then
# -- the generator on fixtures -----------------------------------------------------------------------------------
gen
[ "$rc" = 0 ] && pass "the generator writes the output of the fixtures" || fail "the generator writes the output ($out)"
o="$work/out.ads"
has "the sources are sorted by value and have the value of the SVD" "ALPHA : constant Interrupt_ID := 1;" "$o"
has "a source of another peripheral than the PLIC is there too" "GAMMA : constant Interrupt_ID := 4;" "$o"
has "the description is one line of text" "--  Fifth source" "$o"
"$PY" - "$o" <<'E' && pass "the order is the one of the values" || fail "the order is the one of the values"
import re, sys
names = re.findall(r"^   (\w+) : constant Interrupt_ID", open(sys.argv[1]).read(), re.M)
sys.exit(0 if names == ["ALPHA", "BETA", "GAMMA", "ZETA"] else 1)
E
has "the range is stated as a compile-time check" "Interrupt_ID'First /= 1 or else Interrupt_ID'Last /= 5" "$o"
has "the gap is named in the header" "The PLIC source 3 is reserved or spare in the TRM" "$o"
has "a local interrupt is in the package Local with its own type" "SEVEN : constant Local_Interrupt := 7;" "$o"
has "the type of the local interrupts covers their numbers" "type Local_Interrupt is range 0 .. 7;" "$o"
has "the local interrupts have the offset of the mcause" "Mcause_Offset : constant := 16;" "$o"
has "a local interrupt names its PLIC source" "(E51; also PLIC source ALPHA)" "$o"
has "a local interrupt names its harts" "(U54_1)" "$o"
"$PY" - "$o" <<'E' && pass "local interrupts are sorted by number, then by name" || fail "local interrupts are sorted by number, then by name"
import re, sys
names = re.findall(r"^      (\w+) : constant Local_Interrupt", open(sys.argv[1]).read(), re.M)
sys.exit(0 if names == ["ZERO", "SEVEN", "SEVEN_E51"] else 1)
E
grep -qE 'GENERATED by crates/mpfs_rts/gen_intnam.py' "$o" && pass "the header says that the file is generated" \
  || fail "the header says that the file is generated"
if awk 'length > 79 { bad = 1 } END { exit !bad }' "$o"; then fail "no line is longer than 79 characters"
else pass "no line is longer than 79 characters"; fi

# the same output for another order of the elements and a second run
"$PY" - "$FIX/device.svd" "$work/shuffled.svd" <<'E'
import re, sys
text = open(sys.argv[1]).read()
lines = text.splitlines()
ints = [l for l in lines if "<interrupt>" in l]
rest = [l for l in lines if "<interrupt>" not in l]
at = max(i for i, l in enumerate(rest) if "</peripheral>" in l)
open(sys.argv[2], "w").write("\n".join(rest[:at] + list(reversed(ints)) + rest[at:]) + "\n")
E
SVD="$work/shuffled.svd" OUT="$work/shuffled.ads" gen
cmp -s "$work/out.ads" "$work/shuffled.ads" && pass "the output does not depend on the order of the elements" \
  || fail "the output does not depend on the order of the elements"

gen --check
[ "$rc" = 0 ] && pass "--check of a current output passes" || fail "--check of a current output passes ($rc: $out)"
cp "$work/out.ads" "$work/changed.ads"; echo "--  hand edit" >> "$work/changed.ads"
OUT="$work/changed.ads" gen --check
{ [ "$rc" = 1 ] && printf '%s' "$out" | grep -q "is not current"; } && pass "--check of an edited output fails" \
  || fail "--check of an edited output fails ($rc: $out)"
cmp -s "$work/changed.ads" "$work/out.ads" && fail "--check does not write" || pass "--check does not write the file"
OUT="$work/none.ads" gen --check
[ "$rc" = 1 ] && pass "--check of a missing output fails" || fail "--check of a missing output fails ($rc: $out)"

# -- inputs that are refused ---------------------------------------------------------------------------------------
# svd_with <description> <pattern> <sed program>: the SVD of the fixtures changed by sed
svd_with () {
  sed -e "$3" "$FIX/device.svd" > "$work/bad.svd"
  SVD="$work/bad.svd" gen
  refused "$1" "$2"
}
svd_with "a double value is refused" "value 5 is used by" 's|<value>4</value>|<value>5</value>|'
svd_with "a double name is refused" "name ALPHA has the values" 's|<name>BETA</name>|<name>ALPHA</name>|'
svd_with "a reserved word is refused" "NEW is an Ada reserved word" 's|<name>BETA</name>|<name>NEW</name>|'
svd_with "a lower-case name is refused" "is not an upper-case Ada identifier" 's|<name>BETA</name>|<name>Beta</name>|'
svd_with "a name with a double underscore is refused" "is not an upper-case Ada identifier" 's|<name>BETA</name>|<name>BE__TA</name>|'
svd_with "a first source that is not 1 is refused" "not 1" 's|<value>1</value>|<value>9</value>|'
svd_with "a value that is no number is refused" "no numeric value" 's|<value>2</value>|<value>x</value>|'
printf '<device><peripherals/></device>\n' > "$work/none.svd"
SVD="$work/none.svd" gen; refused "an SVD without an interrupt is refused" "no <interrupt> element"
printf 'not xml\n' > "$work/garbage.svd"
SVD="$work/garbage.svd" gen; refused "an SVD that is no XML is refused" "cannot read the SVD"
SVD="$work/missing.svd" gen; refused "a missing SVD is refused" "cannot read the SVD"

for range in "1 .. 4:one too small" "1 .. 6:one too large" "2 .. 5:a first source that is not 1"; do
  sed -e "s|range 1 .. 5|range ${range%%:*}|" "$FIX/parameters.ads" > "$work/params.ads"
  PARAMS="$work/params.ads" gen
  refused "an Interrupt_Range of ${range%%:*} (${range#*:}) is refused" "Interrupt_Range is ${range%%:*}"
done
sed -e 's|Interrupt_Range|Other_Range|' "$FIX/parameters.ads" > "$work/params.ads"
PARAMS="$work/params.ads" gen; refused "a file without Interrupt_Range is refused" "no declaration of Interrupt_Range"
PARAMS="$work/missing.ads" gen; refused "a missing parameter file is refused" "cannot read"

local_with () {
  sed -e "$3" "$FIX/local.yaml" > "$work/bad.yaml"
  LOCAL="$work/bad.yaml" gen
  refused "$1" "$2"
}
local_with "a local interrupt of an unknown hart is refused" "harts must be" 's|harts: \[E51\]|harts: [E52]|'
local_with "a local interrupt with an unknown PLIC source is refused" "which is no PLIC source" 's|plic: ALPHA|plic: ALFA|'
local_with "a double local name is refused" "the name is used twice" 's|name: SEVEN_E51|name: SEVEN|'
local_with "a wrong schema is refused" "not a local interrupt file of schema 1" 's|schema: 1|schema: 2|'
local_with "a local name that is a reserved word is refused" "TASK is an Ada reserved word" 's|name: ZERO|name: TASK|'
local_with "a negative local number is refused" "local is not a number" 's|local: 0|local: -1|'
LOCAL="$work/missing.yaml" gen; refused "a missing local interrupt file is refused" "cannot read"

# -- the committed file ------------------------------------------------------------------------------------------------
if "$PY" "$ROOT/tools/svd.py" ensure >"$work/svd.out" 2>&1; then
  out="$("$PY" "$GEN" --check 2>&1)"; rc=$?
  [ "$rc" = 0 ] && pass "the committed a-intnam.ads is what the generator makes of the SVD" \
    || fail "the committed a-intnam.ads is what the generator makes of the SVD ($rc: $out)"
else
  skip "the committed file against the SVD: the merged SVD cannot be made ($(head -1 "$work/svd.out"))"
fi
n="$(grep -c ' : constant Interrupt_ID := ' "$COMMITTED")"
[ "$n" = 185 ] && pass "the committed file has 185 PLIC names" || fail "the committed file has 185 PLIC names ($n)"
grep -q "Interrupt_ID'First /= 1 or else Interrupt_ID'Last /= 186" "$COMMITTED" \
  && pass "and states the range 1 .. 186" || fail "and states the range 1 .. 186"
grep -q 'constant Interrupt_ID := 117;' "$COMMITTED" && fail "source 117 has no name" || pass "source 117 has no name"
grep -qE 'subtype Interrupt_Range is Natural range 1 \.\. 186;' "$ROOT/crates/bb-runtimes/src/s-bbpara__polarfiresoc.ads" \
  && pass "Interrupt_Range of s-bbpara is 1 .. 186" || fail "Interrupt_Range of s-bbpara is 1 .. 186"
"$PY" "$GEN" --svd "$FIX/device.svd" --local "$FIX/local.yaml" --parameters "$FIX/parameters.ads" \
  --output "$COMMITTED" --check >/dev/null 2>&1 && fail "--check of the fixtures against the committed file fails" \
  || pass "--check of other inputs against the committed file fails"
else
  skip "the generator: PyYAML is not installed (./x toolchain install)"
fi

# -- the runtime variant and the compiler ----------------------------------------------------------------------------
if ! command -v riscv64-elf-gcc >/dev/null 2>&1 || ! command -v zstd >/dev/null 2>&1 \
   || ! tar --version 2>&1 | grep -q 'GNU tar'; then
  skip "the variant: the pinned toolchain, zstd or GNU tar is not installed"
  echo "summary: $fails failure(s)"; [ $fails -eq 0 ]; exit
fi
if ! bash "$ROOT/tools/pac.sh" ensure >"$work/pac.out" 2>&1; then
  cat "$work/pac.out" >&2
  fail "libs/mpfs_pac/src/generated cannot be generated (./x toolchain install pac)"
  echo "summary: $fails failure(s)"; exit 1
fi
if ! bash "$ROOT/crates/mpfs_rts/gen_runtime.sh" light-tasking u54 1 m >"$work/gen.out" 2>&1; then
  cat "$work/gen.out" >&2; fail "gen_runtime.sh light-tasking u54 1 m"
  echo "summary: $fails failure(s)"; exit 1
fi
rts="$ROOT/build/rts/light-tasking-u54-cpus1-m"
cmp -s "$rts/adainclude/a-intnam.ads" "$COMMITTED" && pass "the variant has the generated a-intnam.ads (not the upstream one)" \
  || fail "the variant has the generated a-intnam.ads"
[ -f "$rts/adalib/a-intnam.ali" ] && pass "the runtime compiles a-intnam.ads (the range check is part of the library)" \
  || fail "the runtime compiles a-intnam.ads"

ARCH=(-march=rv64imafdc_zicsr_zifencei -mabi=lp64d)
# build <case> <flags...>: compile fixtures/<case>.adb against the variant; $rc, $out
build () {
  local f="$1"; shift
  out="$(cd "$work" && riscv64-elf-gcc -c "${ARCH[@]}" --RTS="$rts" -gnatwa -gnatwe "$@" -o "$work/$f.o" "$FIX/$f.adb" 2>&1)"
  rc=$?
}
build bounds_ok
[ "$rc" = 0 ] && pass "control: sources 1, 117 and 186 and the generated names are accepted" \
  || fail "control: sources 1, 117 and 186 and the generated names are accepted ($out)"
build bounds_zero
{ [ "$rc" != 0 ] && printf '%s' "$out" | grep -q 'not in range\|out of range\|Constraint_Error'; } \
  && pass "source 0 (below Interrupt_Range) is rejected" || fail "source 0 (below Interrupt_Range) is rejected ($rc: $out)"
build bounds_high
{ [ "$rc" != 0 ] && printf '%s' "$out" | grep -q 'not in range\|out of range\|Constraint_Error'; } \
  && pass "source 187 (above Interrupt_Range) is rejected" || fail "source 187 (above Interrupt_Range) is rejected ($rc: $out)"
build local_as_id
{ [ "$rc" != 0 ] && printf '%s' "$out" | grep -q 'expected type'; } \
  && pass "a local interrupt number is not an Interrupt_ID" || fail "a local interrupt number is not an Interrupt_ID ($rc: $out)"

# a copy of a-intnam.ads for another range does not compile against this runtime
mkdir -p "$work/other"
sed -e "s|Interrupt_ID'Last /= 186|Interrupt_ID'Last /= 185|" "$COMMITTED" > "$work/other/a-intnam.ads"
out="$(cd "$work/other" && riscv64-elf-gcc -c "${ARCH[@]}" --RTS="$rts" -gnatg -gnatc a-intnam.ads 2>&1)"; rc=$?
{ [ "$rc" != 0 ] && printf '%s' "$out" | grep -q 'Interrupt_Range of System.BB.Parameters is not the range of the PLIC sources'; } \
  && pass "an a-intnam.ads for another range is rejected by its compile-time check" \
  || fail "an a-intnam.ads for another range is rejected by its compile-time check ($rc: $out)"
out="$(cd "$work/other" && cp "$COMMITTED" a-intnam.ads && riscv64-elf-gcc -c "${ARCH[@]}" --RTS="$rts" -gnatg -gnatc a-intnam.ads 2>&1)"; rc=$?
[ "$rc" = 0 ] && pass "control: the committed a-intnam.ads compiles with the style checks of the runtime" \
  || fail "control: the committed a-intnam.ads compiles with the style checks of the runtime ($out)"

echo "summary: $fails failure(s)"
[ $fails -eq 0 ]
