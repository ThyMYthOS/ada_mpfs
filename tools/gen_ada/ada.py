"""What a generator of Ada source needs to write.

  identifier(name, where)       a name from an input as an Ada identifier, or an error
  comment(text, indent)         a comment, wrapped at WIDTH columns
  banner(title)                 the three-line box above a section
  generated_notice(by, inputs)  the "generated, do not edit" paragraph

The header with the licence tags is gen_ada.spdx.
"""
import re

from .errors import GenError, InputError

# A name taken from an input must be usable as it is: upper case, no double or trailing underscore.
IDENTIFIER = re.compile(r"[A-Z][A-Z0-9]*(_[A-Z0-9]+)*")
RESERVED = frozenset("""
    abort abs abstract accept access aliased all and array at begin body case constant declare delay
    delta digits do else elsif end entry exception exit for function generic goto if in interface is
    limited loop mod new not null of or others out overriding package parallel pragma private
    procedure protected raise range record rem renames requeue return reverse select separate
    some subtype synchronized tagged task terminate then type until use when while with xor
""".split())
WIDTH = 78


def identifier(name: str, where: str, error: type[GenError] = InputError) -> str:
    """<name> if it is an upper-case Ada identifier that is not a reserved word, else `error`.

    <where> says where the name comes from, for the message.
    """
    if not IDENTIFIER.fullmatch(name):
        raise error(f"{where}: {name!r} is not an upper-case Ada identifier")
    if name.lower() in RESERVED:
        raise error(f"{where}: {name} is an Ada reserved word")
    return name


def comment(text: str, indent: str = "   ") -> list[str]:
    """A comment of one or more lines, at most WIDTH characters wide (`--  ` after <indent>)."""
    words, lines, line = text.split(), [], ""
    room = WIDTH - len(indent) - 4
    for word in words:
        if line and len(line) + 1 + len(word) > room:
            lines.append(line)
            line = word
        else:
            line = f"{line} {word}".strip()
    if line or not lines:
        lines.append(line)
    return [f"{indent}--  {item}" for item in lines]


def banner(title: str) -> list[str]:
    """The three-line header box of a section."""
    bar = "-" * (len(title) + 6)
    return [f"   {bar}", f"   -- {title} --", f"   {bar}"]


def generated_notice(by: str, inputs: str) -> str:
    """The paragraph that says the file is generated by <by> from <inputs> (a noun phrase), that it must
    not be edited and that CI fails if it is not current. A paragraph for comment()."""
    return (f"GENERATED by {by} from {inputs}. Do not edit: change the inputs and run the generator "
            "(CI fails if this file is not current).")
