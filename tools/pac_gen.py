"""Post-process the output of svd2ada into the register package MPFS_Registers.

  pac_gen.py postprocess DIR --svd SVD --svd-sha256 HASH --svd2ada-commit COMMIT
      Rewrites the svd2ada output in DIR in place, in this order:
        1. verify that every group of peripherals with the same <groupName> in SVD
           (CAN, GPIO, ...) came out as one package with one shared type and one
           instance per member -- svd2ada does the sharing itself; abort if it
           split a group into several types;
        2. add the SPARK volatility aspects to every *_Periph instance, with
           Effective_Reads for the peripherals that have a <readAction> in SVD
           (on a register or a field, also through derivedFrom); abort if such a
           peripheral has no instance in the output or SVD has none at all;
        3. drop `with System;` where it is not needed and add the header.
      The output is deterministic: it does not depend on the time or the host.

  pac_gen.py bases DIR BASES_ADS
      Check that every X_HI_Base of DIR/mpfs_registers.ads is X_LO_Base plus the
      offset HI_Offset declared in BASES_ADS.

  pac_gen.py hash DIR
      Print the SHA-256 of the generated package in DIR (see tree_digest): the value
      that libs/mpfs_pac/MPFS_Registers.sha256 records.

Each step is a function that can be tested on small fixtures
(tests/host/pac/run.sh).
"""
import argparse
import hashlib
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

PACKAGE = "MPFS_Registers"
FILE_PREFIX = PACKAGE.lower() + "-"

SPARK_ASPECTS = ["Volatile", "Async_Readers", "Async_Writers", "Effective_Writes"]

# The tags are assembled so that REUSE does not read them as tags of this file.
_SPDX = "SPDX"
HEADER = (
    f"--  {_SPDX}-FileCopyrightText: 2026 Manuel Stahl <thymythos@googlemail.com>\n"
    f"--  {_SPDX}-License-Identifier: CC-BY-4.0\n"
    "--\n"
    "--  Generated by `./x pac generate` from svd/PolarfireSoC.svd\n"
    "--  (SHA-256 of the SVD: {sha256})\n"
    "--  with svd2ada {commit}. Do not edit.\n"
    "--  The SVD and this register package were created by Manuel Stahl\n"
    "--  (ThyMYthOS/ada_mpfs); attribution as required by CC-BY-4.0.\n"
    "\n"
)

PACKAGE_RE = re.compile(r"^package " + PACKAGE + r"\.(\w+) is$", re.M)
# An instance: the comment lines above it, the declaration and its aspect.
INSTANCE_RE = re.compile(
    r"(?P<comment>(?:^   --  .*\n)+)"
    r"^   (?P<name>\w+)_Periph : aliased (?P<type>\w+)\n"
    r"     with Import, Address => (?P<base>\w+);\n",
    re.M)


class PacError(Exception):
    """A violation that aborts the generation; the message is shown to the user."""


def unit_file(directory: Path, name: str) -> Path:
    return directory / f"{FILE_PREFIX}{name.lower()}.ads"


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


# -- 1. groups of peripherals ---------------------------------------------------

class Peripheral:
    """What pac_gen needs to know about a peripheral of the SVD."""

    def __init__(self, name: str, group: str, reads: bool):
        self.name = name
        self.group = group
        self.reads = reads      # a register or field has a <readAction>


def read_svd(path: Path) -> list[Peripheral]:
    """The peripherals of the SVD in file order. <groupName> and the registers are
    resolved through derivedFrom the way svd2ada does (a derived peripheral
    inherits them from its base)."""
    elements = {p.findtext("name"): p for p in ET.parse(path).getroot().iter("peripheral")}

    def group_of(name: str, seen: tuple[str, ...] = ()) -> str:
        elt = elements[name]
        own = (elt.findtext("groupName") or "").strip()
        base = elt.get("derivedFrom")
        if own or not base or base in seen:
            return own
        return group_of(base, seen + (name,))

    def reads_of(name: str, seen: tuple[str, ...] = ()) -> bool:
        elt = elements[name]
        base = elt.get("derivedFrom")
        return (elt.find(".//readAction") is not None
                or bool(base and base not in seen and reads_of(base, seen + (name,))))

    return [Peripheral(name, group_of(name), reads_of(name)) for name in elements]


def groups_of(peripherals: list[Peripheral]) -> dict[str, list[str]]:
    """Groups with more than one member: group name -> member names."""
    groups: dict[str, list[str]] = {}
    for p in peripherals:
        if p.group:
            groups.setdefault(p.group, []).append(p.name)
    return {g: m for g, m in groups.items() if len(m) > 1}


def check_groups(directory: Path, peripherals: list[Peripheral]) -> int:
    """Verify the packages of the groups; returns their number.

    svd2ada writes the peripherals of one <groupName> into MPFS_Registers.<Group>
    and gives all of them the type <Group>_Peripheral if their registers are
    identical; otherwise it silently keeps one type per layout.
    """
    groups = groups_of(peripherals)
    for group, members in sorted(groups.items()):
        path = unit_file(directory, group)
        if not path.exists():
            raise PacError(f"{group}: svd2ada wrote no package {path.name}")
        found = {m.group("name"): m.group("type") for m in INSTANCE_RE.finditer(read(path))}
        if sorted(found) != sorted(members):
            raise PacError(f"{group}: the package has the instances {sorted(found)}, "
                           f"the SVD has the members {sorted(members)}")
        shared = f"{group}_Peripheral"
        split = sorted(f"{n}: {t}" for n, t in found.items() if t != shared)
        if split:
            raise PacError(f"{group}: the members do not have identical registers, svd2ada "
                           f"did not share {shared}:\n  " + "\n  ".join(split))
    return len(groups)


# -- 2. SPARK aspects --------------------------------------------------------

def annotate_text(text: str, reading: set[str], done: set[str]) -> tuple[str, int]:
    """Add the aspects to every instance of `text`; the names of the instances with
    Effective_Reads are added to `done`."""
    total = 0

    def repl(m: re.Match) -> str:
        nonlocal total
        name = m.group("name")
        aspects = list(SPARK_ASPECTS)
        if name in reading:
            done.add(name)
            aspects.append("Effective_Reads => True")
        total += 1
        tail = ",\n          ".join([", ".join(aspects[:4])] + aspects[4:])
        return (f"{m.group('comment')}   {name}_Periph : aliased {m.group('type')}\n"
                f"     with Import, Address => {m.group('base')},\n          {tail};\n")

    return INSTANCE_RE.sub(repl, text), total


def annotate(directory: Path, peripherals: list[Peripheral]) -> int:
    """Annotate all instances; Effective_Reads comes from the <readAction> of the SVD."""
    reading = {p.name for p in peripherals if p.reads}
    if not reading:
        raise PacError("the SVD has no readAction: no instance would get Effective_Reads")
    done: set[str] = set()
    total = 0
    for path in sorted(directory.glob("*.ads")):
        text = read(path)
        new, n = annotate_text(text, reading, done)
        if n:
            path.write_text(new, encoding="utf-8")
            total += n
    if done != reading:
        raise PacError("peripherals with a readAction in the SVD but no instance in the "
                       "package: " + ", ".join(sorted(reading - done)))
    return total


# -- 3. with System, header --------------------------------------------------

def strip_unused_system(text: str) -> str:
    """Remove `with System;` when nothing else in the text refers to System."""
    without = text.replace("with System;\n\n", "", 1)
    return text if re.search(r"\bSystem\b", without) else without


def finish(directory: Path, sha256: str, commit: str) -> None:
    for path in sorted(directory.glob("*.ads")):
        text = strip_unused_system(read(path))
        path.write_text(HEADER.format(sha256=sha256, commit=commit) + text, encoding="utf-8")


def postprocess(directory: Path, svd: Path, sha256: str, commit: str) -> None:
    peripherals = read_svd(svd)
    check_groups(directory, peripherals)
    annotate(directory, peripherals)
    finish(directory, sha256, commit)


# -- hash of the generated package -------------------------------------------

def tree_digest(directory: Path) -> str:
    """SHA-256 over the *.ads files of <directory>, in name order, each as name, NUL, content, NUL.

    The generated package is not committed; this is the hash recorded in libs/mpfs_pac/MPFS_Registers.sha256, the
    counterpart of svd/PolarfireSoC.sha256. It covers the SVD hash and the svd2ada commit, which the header of
    every file carries.
    """
    files = sorted(directory.glob("*.ads"))
    if not files:
        raise PacError(f"no *.ads file in {directory}")
    h = hashlib.sha256()
    for path in files:
        h.update(path.name.encode() + b"\0" + path.read_bytes() + b"\0")
    return h.hexdigest()


# -- hand-written base address helper ----------------------------------------

def check_bases(directory: Path, bases: Path) -> int:
    """Number of LO/HI pairs checked; raises if HI is not LO + HI_Offset."""
    m = re.search(r"HI_Offset\s*:\s*constant[^:]*:=\s*(16#[0-9A-Fa-f_]+#)", read(bases))
    if not m:
        raise PacError(f"{bases}: no HI_Offset declaration")
    offset = int(m.group(1).replace("_", "").replace("16#", "").rstrip("#"), 16)
    addr = {n: int(a.replace("_", ""), 16) for n, a in re.findall(
        r"^   (\w+_Base) : constant System\.Address := System'To_Address \(16#([0-9A-Fa-f_]+)#\);",
        read(directory / "mpfs_registers.ads"), re.M)}
    pairs = 0
    for name, lo in sorted(addr.items()):
        if name.endswith("_LO_Base"):
            hi = name.replace("_LO_Base", "_HI_Base")
            if hi not in addr:
                raise PacError(f"{hi} is missing")
            if addr[hi] != lo + offset:
                raise PacError(f"{hi} is {addr[hi]:#x}, not {name} + HI_Offset ({lo + offset:#x})")
            pairs += 1
    for name in addr:
        if name.endswith("_HI_Base") and name.replace("_HI_Base", "_LO_Base") not in addr:
            raise PacError(f"{name} has no LO counterpart")
    if pairs == 0:
        raise PacError("no LO/HI base address pair found")
    return pairs


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("postprocess")
    p.add_argument("dir", type=Path)
    p.add_argument("--svd", type=Path, required=True)
    p.add_argument("--svd-sha256", required=True)
    p.add_argument("--svd2ada-commit", required=True)
    b = sub.add_parser("bases")
    b.add_argument("dir", type=Path)
    b.add_argument("bases", type=Path)
    h = sub.add_parser("hash")
    h.add_argument("dir", type=Path)
    args = ap.parse_args(argv[1:])
    try:
        if args.cmd == "postprocess":
            postprocess(args.dir, args.svd, args.svd_sha256, args.svd2ada_commit)
        elif args.cmd == "hash":
            print(tree_digest(args.dir))
        else:
            print(f"pac: {check_bases(args.dir, args.bases)} LO/HI base address pairs ok")
    except PacError as e:
        print(f"pac: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
